import pytest

from jarvis_app.relevance import DEFAULT_MINUS_WORDS, minus_hit, parse_minus_words, stem, tag_matches


@pytest.mark.parametrize(
    "title,tag,ok",
    [
        ("Поставка проекторов для школы", "проектор", True),
        ("Поставка мультимедийного проектора", "проектор", True),
        ("Выполнение работ по проектированию сетей", "проектор", False),
        ("Поставка мультимедийного оборудования", "мультимедиа", True),
        ("Поставка звукового оборудования для ДК", "звуковое оборудование", True),
        ("Поставка оборудования для видеонаблюдения", "звуковое оборудование", False),
        ("Поставка театрального оборудования", "оборудование для театра", True),
        ("Поставка оборудования для драматического театра", "оборудование для театра", True),
        ("Поставка одежды сцены для театра", "оборудование для театра", False),
    ],
)
def test_tag_matches(title, tag, ok):
    assert tag_matches(title, tag) is ok


def test_minus_words():
    assert minus_hit("Поставка медицинского мультимедийного комплекса", DEFAULT_MINUS_WORDS) == "медицин"
    assert minus_hit("Поставка проектора для актового зала", DEFAULT_MINUS_WORDS) == ""
    assert minus_hit("Ремонт автомобильной дороги", ["ремонт дорог"]) == ""  # фраза целиком
    assert minus_hit("Ремонт дорог района", ["ремонт дорог"]) == "ремонт дорог"
    assert parse_minus_words("медицин, хирург;\nстоматолог") == ["медицин", "хирург", "стоматолог"]


def test_stem():
    assert stem("театра") == stem("театр") == "театр"
    assert stem("проекторов") == "проектор"
